"""First-round planner implementation."""

from __future__ import annotations

import json
import re
import uuid
from dataclasses import dataclass, field
from typing import Any, List

from agentscope.message import Msg
from pydantic import BaseModel, ConfigDict, Field

from swarmmind.agents.profile import AgentProfileStore
from swarmmind.agents.config import AgentConfig, AgentScopeConfig
from swarmmind.agents.factory import AgentFactory
from swarmmind.memory import LongTermMemoryBase
from swarmmind.models.capability import (
    AgentRole,
    DEFAULT_ROLE_TOOL_GROUPS,
    RuntimeKind,
    ToolGroup,
)
from swarmmind.models.execution import ExecutionConfiguration
from swarmmind.models.run import Run
from swarmmind.models.task import SubTask, Task
from swarmmind.prompt_template import (
    PLANNER_EXECUTION_CONFIGURATION_PROMPT,
    PLANNER_SYSTEM_PROMPT,
    PLANNER_TASK_DECOMPOSITION_PROMPT,
    PromptTemplate,
    render_prompt,
)


PLANNER_ALLOWED_ROLES: set[AgentRole] = {
    AgentRole.PLANNER,
    AgentRole.CODER,
    AgentRole.VERIFIER,
    AgentRole.TESTER,
    AgentRole.REVIEWER,
    AgentRole.RESEARCHER,
    AgentRole.WRITER,
}


@dataclass(slots=True)
class _NormalizedPlanSubtaskSpec:
    name: str
    description: str
    role: AgentRole
    acceptance_criteria: list[str]
    expected_artifacts: list[str]
    dependencies: list[str]
    execution_configuration: ExecutionConfiguration | None = None
    metadata: dict[str, Any] = field(default_factory=dict)


class Planner:
    """Create a simple task graph from the submitted goal."""

    def __init__(
        self,
        model_name: str = "gpt-4o",
        model_api_key: str | None = None,
        model_base_url: str | None = None,
        model_temperature: float = 0.2,
        model_max_tokens: int = 2048,
        system_prompt_template: PromptTemplate = PLANNER_SYSTEM_PROMPT,
        user_prompt_template: PromptTemplate = PLANNER_TASK_DECOMPOSITION_PROMPT,
        execution_prompt_template: PromptTemplate = PLANNER_EXECUTION_CONFIGURATION_PROMPT,
        agent_profile_store: AgentProfileStore | None = None,
        long_term_memory: LongTermMemoryBase | None = None,
    ) -> None:
        self._model_name = model_name
        self._model_api_key = model_api_key
        self._model_base_url = model_base_url
        self._model_temperature = model_temperature
        self._model_max_tokens = model_max_tokens
        self._system_prompt_template = system_prompt_template
        self._user_prompt_template = user_prompt_template
        self._execution_prompt_template = execution_prompt_template
        self._agent_profile_store = agent_profile_store
        self._long_term_memory = long_term_memory

    async def plan(self, task: Task, run: Run) -> List[SubTask]:
        """Return a task graph generated by model when available, with deterministic fallback."""
        llm_subtasks = await self._plan_with_model(task, run)
        if llm_subtasks:
            return llm_subtasks
        return self._fallback_subtasks(task, run)

    async def _plan_with_model(self, task: Task, run: Run) -> List[SubTask]:

        try:
            agent_factory = AgentFactory(
                AgentConfig(
                    name="planner-agent",
                    scope_config=AgentScopeConfig(
                        model_name=self._model_name,
                        api_key=self._model_api_key,
                        base_url=self._model_base_url,
                        temperature=self._model_temperature,
                        max_tokens=self._model_max_tokens,
                    ),
                    max_steps=3,
                    system_prompt=render_prompt(self._system_prompt_template),
                )
            )
            agent = agent_factory.create_main_agent(tools=[])
            prompt = await self._compose_planning_prompt(task)
            result = await agent(Msg(name="user", role="user", content=prompt))
            text = result.get_text_content() or json.dumps(result.to_dict(), ensure_ascii=False)
            payload = self._extract_json_payload(text)
            if payload is None:
                return []

            plan_result = _PlanResult.model_validate(payload)
            normalized_plan = self._validate_and_normalize_plan(task, plan_result)
            execution_configuration = await self._plan_execution_configurations(task, normalized_plan, agent)
            enriched_plan = self._merge_execution_configurations(task, normalized_plan, execution_configuration)
            return self._build_subtasks_from_plan(task, run, enriched_plan)
        except Exception:
            return []

    async def _compose_planning_prompt(self, task: Task) -> str:
        prompt = render_prompt(
            self._user_prompt_template,
            {
                "task_goal": task.goal,
                "constraints_json": json.dumps(task.constraints, ensure_ascii=False),
                "agent_profiles_json": json.dumps(self._render_agent_profile_options(), ensure_ascii=False),
                "role_definitions": AgentRole.to_prompt_definitions(),
            },
        )
        memory_context = await self._render_memory_context(task.goal)
        if not memory_context:
            return prompt
        return f"{prompt}\n\nRelevant long-term memory:\n{memory_context}"

    async def _render_memory_context(self, query: str) -> str:
        if self._long_term_memory is None:
            return ""
        try:
            items = await self._long_term_memory.retrieve(query, top_k=3)
        except Exception:
            return ""
        if not items:
            return ""
        return "\n".join(f"- {item.content[:280]}" for item in items)

    async def _compose_execution_configuration_prompt(
        self,
        task: Task,
        plan_specs: list[_NormalizedPlanSubtaskSpec],
    ) -> str:
        subtasks_json = json.dumps(
            {
                "subtasks": [
                    {
                        "name": spec.name,
                        "description": spec.description,
                        "role": spec.role.value,
                        "acceptance_criteria": spec.acceptance_criteria,
                        "expected_artifacts": spec.expected_artifacts,
                        "dependencies": spec.dependencies,
                    }
                    for spec in plan_specs
                ]
            },
            ensure_ascii=False,
        )
        return render_prompt(
            self._execution_prompt_template,
            {
                "task_goal": task.goal,
                "constraints_json": json.dumps(task.constraints, ensure_ascii=False),
                "profile": str(task.metadata.get("profile", "py-basic")),
                "subtasks_json": subtasks_json,
                "agent_profiles_json": json.dumps(self._render_agent_profile_options(), ensure_ascii=False),
                "role_definitions": AgentRole.to_prompt_definitions(),
            },
        )

    @staticmethod
    def _extract_json_payload(raw_text: str) -> dict[str, object] | None:
        fenced = re.search(r"```(?:json)?\\s*(\{.*\})\\s*```", raw_text, flags=re.DOTALL | re.IGNORECASE)
        candidate = fenced.group(1) if fenced else raw_text
        start = candidate.find("{")
        end = candidate.rfind("}")
        if start == -1 or end == -1 or end < start:
            return None
        snippet = candidate[start : end + 1]
        try:
            value = json.loads(snippet)
        except json.JSONDecodeError:
            return None
        if isinstance(value, dict):
            return value
        return None

    def _validate_and_normalize_plan(self, task: Task, plan_result: "_PlanResult") -> list[_NormalizedPlanSubtaskSpec]:
        return [self._normalize_plan_subtask(task, spec) for spec in plan_result.subtasks]

    async def _plan_execution_configurations(
        self,
        task: Task,
        plan_specs: list[_NormalizedPlanSubtaskSpec],
        agent,
    ) -> list["_ExecutionConfigurationSubtaskSpec"]:
        prompt = await self._compose_execution_configuration_prompt(task, plan_specs)
        result = await agent(Msg(name="user", role="user", content=prompt))
        text = result.get_text_content() or json.dumps(result.to_dict(), ensure_ascii=False)
        payload = self._extract_json_payload(text)
        if payload is None:
            return []
        config_result = _ExecutionConfigurationResult.model_validate(payload)
        return list(config_result.subtasks)

    def _merge_execution_configurations(
        self,
        task: Task,
        plan_specs: list[_NormalizedPlanSubtaskSpec],
        execution_specs: list["_ExecutionConfigurationSubtaskSpec"],
    ) -> list[_NormalizedPlanSubtaskSpec]:
        normalized_by_name: dict[str, ExecutionConfiguration] = {}
        for execution_spec in execution_specs:
            normalized_name = self._normalize_name(execution_spec.name)
            if not normalized_name:
                continue
            normalized_by_name[normalized_name] = self._normalize_execution_configuration(task, execution_spec)

        merged: list[_NormalizedPlanSubtaskSpec] = []
        for spec in plan_specs:
            execution_configuration = normalized_by_name.get(self._normalize_name(spec.name))
            if execution_configuration is None:
                execution_configuration = self._default_execution_configuration(task, spec.role)
            merged.append(
                _NormalizedPlanSubtaskSpec(
                    name=spec.name,
                    description=spec.description,
                    role=spec.role,
                    acceptance_criteria=spec.acceptance_criteria,
                    expected_artifacts=spec.expected_artifacts,
                    dependencies=spec.dependencies,
                    execution_configuration=execution_configuration,
                    metadata=dict(spec.metadata),
                )
            )
        return merged

    def _build_subtasks_from_plan(
        self,
        task: Task,
        run: Run,
        plan_result: "_PlanResult | list[_NormalizedPlanSubtaskSpec]",
    ) -> list[SubTask]:
        normalized_specs = (
            self._validate_and_normalize_plan(task, plan_result)
            if isinstance(plan_result, _PlanResult)
            else plan_result
        )

        normalized: list[tuple[str, _NormalizedPlanSubtaskSpec]] = []
        used_names: set[str] = set()

        for spec in normalized_specs:
            normalized_name = self._normalize_name(spec.name)
            if not normalized_name:
                normalized_name = "subtask"
            base_name = normalized_name
            suffix = 2
            while normalized_name in used_names:
                normalized_name = f"{base_name}-{suffix}"
                suffix += 1
            used_names.add(normalized_name)
            normalized.append((normalized_name, spec))

        name_to_id = {name: str(uuid.uuid4()) for name, _ in normalized}
        subtasks: list[SubTask] = []

        for name, spec in normalized:
            dependencies = [name_to_id[d] for d in spec.dependencies if d in name_to_id and d != name]
            acceptance_criteria = [item.strip() for item in spec.acceptance_criteria if item.strip()]
            if not acceptance_criteria:
                acceptance_criteria = ["Subtask output is complete and verifiable."]
            metadata = {
                "run_id": run.id,
                "plan_source": "llm",
                "planning_prompt": self._user_prompt_template.name,
                **spec.metadata,
            }
            metadata["execution_configuration"] = (
                spec.execution_configuration.model_dump(mode="json")
                if spec.execution_configuration is not None
                else None
            )

            subtasks.append(
                SubTask(
                    id=name_to_id[name],
                    task_id=task.id,
                    name=name,
                    description=spec.description.strip() or f"Execute {name}",
                    role=spec.role,
                    acceptance_criteria=acceptance_criteria,
                    expected_artifacts=list(spec.expected_artifacts),
                    execution_configuration=spec.execution_configuration,
                    dependencies=dependencies,
                    metadata=metadata,
                )
            )

        return subtasks

    def _normalize_plan_subtask(self, task: Task, spec: "_PlanSubtaskSpec") -> _NormalizedPlanSubtaskSpec:
        warnings: list[str] = []
        metadata: dict[str, Any] = {}

        role = self._parse_role(spec.role)
        if spec.role and (spec.role.strip().lower() != role.value or role not in PLANNER_ALLOWED_ROLES):
            warnings.append(f"Normalized invalid planner role '{spec.role}' to '{role.value}'.")
            metadata["original_role"] = spec.role
        elif role not in PLANNER_ALLOWED_ROLES:
            warnings.append(f"Planner role '{role.value}' is not supported for subtasks; using 'coder'.")
            metadata["original_role"] = spec.role
            role = AgentRole.CODER

        expected_artifacts = self._normalize_string_list(spec.expected_artifacts)
        if not expected_artifacts:
            expected_artifacts = ["deliverable"]
            warnings.append("Fell back to a default expected_artifacts entry.")

        if warnings:
            metadata["planner_validation_warnings"] = warnings

        return _NormalizedPlanSubtaskSpec(
            name=spec.name,
            description=spec.description,
            role=role,
            acceptance_criteria=spec.acceptance_criteria,
            expected_artifacts=expected_artifacts,
            dependencies=spec.dependencies,
            metadata=metadata,
        )

    @staticmethod
    def _parse_role(value: str | None) -> AgentRole:
        if not value:
            return AgentRole.CODER
        try:
            role = AgentRole(str(value).strip().lower())
        except ValueError:
            return AgentRole.CODER
        if role not in PLANNER_ALLOWED_ROLES:
            return AgentRole.CODER
        return role

    @staticmethod
    def _parse_tool_groups(values: list[str]) -> list[ToolGroup]:
        parsed: list[ToolGroup] = []
        for value in values:
            token = str(value).strip().lower()
            try:
                tool_group = ToolGroup(token)
            except ValueError:
                continue
            if tool_group not in parsed:
                parsed.append(tool_group)
        return parsed

    @staticmethod
    def _parse_runtime_kinds(values: list[str]) -> list[RuntimeKind]:
        parsed: list[RuntimeKind] = []
        for value in values:
            token = str(value).strip().lower()
            try:
                runtime_kind = RuntimeKind(token)
            except ValueError:
                continue
            if runtime_kind not in parsed:
                parsed.append(runtime_kind)
        return parsed

    @staticmethod
    def _normalize_skill_profiles(values: list[str]) -> list[str]:
        normalized: list[str] = []
        for value in values:
            token = str(value).strip()
            if token and token not in normalized:
                normalized.append(token)
        return normalized

    @staticmethod
    def _normalize_string_list(values: list[str]) -> list[str]:
        normalized: list[str] = []
        for value in values:
            token = str(value).strip()
            if token and token not in normalized:
                normalized.append(token)
        return normalized

    @staticmethod
    def _default_tool_groups_for_role(role: AgentRole) -> list[ToolGroup]:
        return list(DEFAULT_ROLE_TOOL_GROUPS.get(role, [ToolGroup.WORKSPACE]))

    @staticmethod
    def _normalize_name(name: str) -> str:
        token = (name or "").strip().lower()
        token = re.sub(r"[^a-z0-9]+", "-", token)
        token = token.strip("-")
        return token

    def _render_agent_profile_options(self) -> list[dict[str, str | bool | None]]:
        if self._agent_profile_store is None:
            return []
        return [
            {
                "id": profile.id,
                "role": profile.role.value,
                "allow_handoff": profile.handoff_policy.allow_handoff,
            }
            for profile in self._agent_profile_store.list_all()
        ]

    @staticmethod
    def _normalize_optional_string(value: str | None) -> str | None:
        if value is None:
            return None
        token = str(value).strip()
        return token or None

    def _default_execution_configuration(self, task: Task, role: AgentRole) -> ExecutionConfiguration:
        tool_requirements = self._default_tool_groups_for_role(role)
        runtime_kind = RuntimeKind.SANDBOX if ToolGroup.CODE_EXEC in tool_requirements else RuntimeKind.HOST_TOOLS
        skill_profiles: list[str] = []
        sandbox_profile = str(task.metadata.get("profile", "py-basic")) if runtime_kind == RuntimeKind.SANDBOX else None
        if self._agent_profile_store is not None:
            profile = self._agent_profile_store.resolve_for_subtask(profile_id=None, role=role)
            if profile.default_tool_groups:
                tool_requirements = list(profile.default_tool_groups)
            if profile.recommended_runtime_kinds:
                runtime_kind = profile.recommended_runtime_kinds[0]
            skill_profiles = list(profile.skill_profiles)
            if runtime_kind == RuntimeKind.SANDBOX:
                sandbox_profile = profile.default_sandbox_profile or sandbox_profile
        if runtime_kind != RuntimeKind.SANDBOX:
            sandbox_profile = None
        return ExecutionConfiguration(
            runtime_kind=runtime_kind,
            tool_requirements=tool_requirements,
            sandbox_profile=sandbox_profile,
            skill_profiles=skill_profiles,
        )

    def _normalize_execution_configuration(
        self,
        task: Task,
        spec: "_ExecutionConfigurationSubtaskSpec",
    ) -> ExecutionConfiguration:
        tool_requirements = self._parse_tool_groups(spec.tool_requirements)
        runtime_kind = None
        if spec.runtime_kind:
            try:
                runtime_kind = RuntimeKind(spec.runtime_kind.strip().lower())
            except ValueError:
                runtime_kind = None
        sandbox_profile = self._normalize_optional_string(spec.sandbox_profile)
        skill_profiles = self._normalize_skill_profiles(spec.skill_profiles)
        if runtime_kind == RuntimeKind.SANDBOX:
            sandbox_profile = sandbox_profile or str(task.metadata.get("profile", "py-basic"))
        else:
            sandbox_profile = None
        return ExecutionConfiguration(
            runtime_kind=runtime_kind,
            tool_requirements=tool_requirements,
            sandbox_profile=sandbox_profile,
            skill_profiles=skill_profiles,
        )

    def _fallback_subtasks(self, task: Task, run: Run) -> list[SubTask]:
        fallback_specs = [
            _NormalizedPlanSubtaskSpec(
                name="analyze-requirement",
                description="Analyze the task requirements and identify the implementation scope.",
                role=AgentRole.PLANNER,
                acceptance_criteria=["Requirements summary is clear and implementation scope is identified."],
                expected_artifacts=["analysis_note"],
                dependencies=[],
                execution_configuration=self._default_execution_configuration(task, AgentRole.PLANNER),
                metadata={"plan_source": "rules"},
            ),
            _NormalizedPlanSubtaskSpec(
                name="prepare-implementation",
                description="Implement the required changes for the task.",
                role=AgentRole.CODER,
                acceptance_criteria=["Implementation changes are complete and locally verifiable."],
                expected_artifacts=["code_changes"],
                dependencies=["analyze-requirement"],
                execution_configuration=self._default_execution_configuration(task, AgentRole.CODER),
                metadata={"plan_source": "rules"},
            ),
            _NormalizedPlanSubtaskSpec(
                name="verify-result",
                description="Verify the implementation against the acceptance criteria.",
                role=AgentRole.TESTER,
                acceptance_criteria=["Verification evidence is attached and acceptance criteria are checked."],
                expected_artifacts=["verification_report"],
                dependencies=["prepare-implementation"],
                execution_configuration=self._default_execution_configuration(task, AgentRole.TESTER),
                metadata={"plan_source": "rules"},
            ),
            _NormalizedPlanSubtaskSpec(
                name="review-result",
                description="Review the verified result and decide accept or rework.",
                role=AgentRole.REVIEWER,
                acceptance_criteria=["Review decision is recorded."],
                expected_artifacts=["review_decision"],
                dependencies=["verify-result"],
                execution_configuration=self._default_execution_configuration(task, AgentRole.REVIEWER),
                metadata={"plan_source": "rules"},
            ),
        ]
        return self._build_subtasks_from_plan(task, run, fallback_specs)


class _PlanSubtaskSpec(BaseModel):
    name: str = Field(...)
    description: str = Field(default="")
    role: str = Field(default="coder")
    model_config = ConfigDict(populate_by_name=True)

    acceptance_criteria: list[str] = Field(default_factory=list)
    expected_artifacts: list[str] = Field(default_factory=list)
    dependencies: list[str] = Field(default_factory=list)

class _PlanResult(BaseModel):
    subtasks: list[_PlanSubtaskSpec] = Field(default_factory=list)


class _ExecutionConfigurationSubtaskSpec(BaseModel):
    name: str = Field(...)
    runtime_kind: str | None = Field(default=None)
    tool_requirements: list[str] = Field(default_factory=list)
    sandbox_profile: str | None = Field(default=None)
    skill_profiles: list[str] = Field(default_factory=list)


class _ExecutionConfigurationResult(BaseModel):
    subtasks: list[_ExecutionConfigurationSubtaskSpec] = Field(default_factory=list)
